import fs from "node:fs";
import path from "node:path";
import {
  ComponentMetaSchema,
  StyleMetaSchema,
  type CatalogComponentEntry,
  type CatalogStyleEntry,
  type ComponentKind,
  type RakitekCatalog,
} from "../registry/schema";

const ROOT = path.resolve(process.cwd());
const REGISTRY_DIR = path.join(ROOT, "registry");
const GEN_REGISTRY_DIR = path.join(REGISTRY_DIR, ".generated");
const WEB_GEN_DIR = path.join(ROOT, "apps", "web", "src", "generated");

function ensureDir(dir: string) {
  fs.mkdirSync(dir, { recursive: true });
}

function listSubdirs(parent: string): string[] {
  if (!fs.existsSync(parent)) return [];
  return fs
    .readdirSync(parent, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("."))
    .map((entry) => entry.name)
    .sort();
}

function readJson(filePath: string): unknown {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function loadStyles(): { entries: CatalogStyleEntry[]; cssParts: string[]; fontImports: string[] } {
  const stylesDir = path.join(REGISTRY_DIR, "styles");
  const entries: CatalogStyleEntry[] = [];
  const cssParts: string[] = [];
  const fontImports: string[] = [];

  for (const dirName of listSubdirs(stylesDir)) {
    const itemDir = path.join(stylesDir, dirName);
    const metaPath = path.join(itemDir, "meta.json");
    const tokensPath = path.join(itemDir, "tokens.css");
    if (!fs.existsSync(metaPath) || !fs.existsSync(tokensPath)) {
      throw new Error(`Style "${dirName}" must contain both meta.json and tokens.css`);
    }

    const parsed = StyleMetaSchema.parse(readJson(metaPath));
    if (parsed.id !== dirName) {
      throw new Error(`Style folder "${dirName}" does not match meta.id "${parsed.id}"`);
    }

    const relTokens = path.relative(ROOT, tokensPath).replaceAll("\\", "/");
    entries.push({ ...parsed, tokensPath: relTokens });

    fontImports.push(`@import url("${parsed.fonts.googleFontsUrl}");`);
    cssParts.push(`/* Style: ${parsed.id} */\n${fs.readFileSync(tokensPath, "utf8").trim()}`);
  }

  return { entries, cssParts, fontImports };
}

const CORE_FILES = new Set(["meta.json", "component.tsx", "preview.tsx", "styles.module.css"]);
const EXTRA_FILE_EXTS = new Set([".ts", ".tsx", ".css"]);

function collectExtraFiles(itemDir: string): Array<{ name: string; path: string }> {
  return fs
    .readdirSync(itemDir, { withFileTypes: true })
    .filter(
      (entry) =>
        entry.isFile() &&
        !CORE_FILES.has(entry.name) &&
        EXTRA_FILE_EXTS.has(path.extname(entry.name)),
    )
    .map((entry) => ({
      name: entry.name,
      path: path.relative(ROOT, path.join(itemDir, entry.name)).replaceAll("\\", "/"),
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

const KIND_TO_FOLDER: Record<ComponentKind, string> = {
  ui: "ui",
  section: "sections",
  template: "templates",
  page: "pages",
};

function loadComponents(kind: ComponentKind): CatalogComponentEntry[] {
  const folder = KIND_TO_FOLDER[kind];
  const baseDir = path.join(REGISTRY_DIR, folder);
  const entries: CatalogComponentEntry[] = [];

  for (const dirName of listSubdirs(baseDir)) {
    const itemDir = path.join(baseDir, dirName);
    const metaPath = path.join(itemDir, "meta.json");
    const compPath = path.join(itemDir, "component.tsx");
    const prevPath = path.join(itemDir, "preview.tsx");
    const stylesModPath = path.join(itemDir, "styles.module.css");

    if (!fs.existsSync(metaPath) || !fs.existsSync(compPath) || !fs.existsSync(prevPath)) {
      throw new Error(
        `${kind} "${dirName}" must contain meta.json, component.tsx, and preview.tsx`,
      );
    }

    const parsed = ComponentMetaSchema.parse(readJson(metaPath));
    if (parsed.id !== dirName || parsed.kind !== kind) {
      throw new Error(
        `${kind} "${dirName}" has mismatched id ("${parsed.id}") or kind ("${parsed.kind}")`,
      );
    }

    const hasStylesMod = fs.existsSync(stylesModPath);
    const extraFiles = collectExtraFiles(itemDir);
    entries.push({
      ...parsed,
      componentPath: path.relative(ROOT, compPath).replaceAll("\\", "/"),
      previewPath: path.relative(ROOT, prevPath).replaceAll("\\", "/"),
      ...(hasStylesMod
        ? { stylesPath: path.relative(ROOT, stylesModPath).replaceAll("\\", "/") }
        : {}),
      ...(extraFiles.length > 0 ? { extraFiles } : {}),
    });
  }

  return entries;
}

function writePreviewMap(items: CatalogComponentEntry[]) {
  const lines = [
    "// Generated by scripts/sync-registry.ts.",
    'import type { ComponentType } from "react";',
    "",
    "export const PREVIEW_LOADERS: Record<string, () => Promise<{ default: ComponentType }>> = {",
  ];

  for (const item of items) {
    const key = `${item.kind}/${item.id}`;
    const importTarget = `../../../../${item.previewPath.replace(/\.tsx$/, "")}`;
    lines.push(`  "${key}": () => import("${importTarget}"),`);
  }

  lines.push("};", "");
  fs.writeFileSync(path.join(WEB_GEN_DIR, "preview-map.ts"), lines.join("\n"), "utf8");
}

function writeSourcesJson(catalog: RakitekCatalog) {
  const sources: Record<
    string,
    {
      code: string;
      stylesCss?: string;
      preview?: string;
      extraFiles?: Record<string, string>;
    }
  > = {};

  for (const style of catalog.styles) {
    sources[`style/${style.id}`] = {
      code: fs.readFileSync(path.join(ROOT, style.tokensPath), "utf8"),
    };
  }

  for (const item of [...catalog.ui, ...catalog.sections, ...catalog.templates, ...catalog.pages]) {
    const extraFiles =
      item.extraFiles && item.extraFiles.length > 0
        ? Object.fromEntries(
            item.extraFiles.map((file) => [
              file.name,
              fs.readFileSync(path.join(ROOT, file.path), "utf8"),
            ]),
          )
        : undefined;

    sources[`${item.kind}/${item.id}`] = {
      code: fs.readFileSync(path.join(ROOT, item.componentPath), "utf8"),
      ...(item.stylesPath
        ? { stylesCss: fs.readFileSync(path.join(ROOT, item.stylesPath), "utf8") }
        : {}),
      preview: fs.readFileSync(path.join(ROOT, item.previewPath), "utf8"),
      ...(extraFiles ? { extraFiles } : {}),
    };
  }

  fs.writeFileSync(
    path.join(WEB_GEN_DIR, "sources.json"),
    JSON.stringify(sources, null, 2) + "\n",
    "utf8",
  );
}

function main() {
  ensureDir(GEN_REGISTRY_DIR);
  ensureDir(WEB_GEN_DIR);

  const { entries: styles, cssParts } = loadStyles();
  const ui = loadComponents("ui");
  const sections = loadComponents("section");
  const templates = loadComponents("template");
  const pages = loadComponents("page");

  const catalog: RakitekCatalog = {
    generatedAt: new Date().toISOString(),
    styles,
    ui,
    sections,
    templates,
    pages,
  };

  const catalogJson = JSON.stringify(catalog, null, 2) + "\n";
  fs.writeFileSync(path.join(GEN_REGISTRY_DIR, "catalog.json"), catalogJson, "utf8");
  fs.writeFileSync(path.join(WEB_GEN_DIR, "catalog.json"), catalogJson, "utf8");

  const bundleCss = [
    "/* Generated by scripts/sync-registry.ts. */",
    "",
    ...cssParts,
    "",
  ].join("\n");
  fs.writeFileSync(path.join(WEB_GEN_DIR, "styles-bundle.css"), bundleCss, "utf8");

  writePreviewMap([...ui, ...sections, ...templates, ...pages]);
  writeSourcesJson(catalog);

  console.log(
    `[rakitek sync] Synced ${styles.length} styles, ${ui.length} UI, ${sections.length} sections, ${templates.length} templates, ${pages.length} pages.`,
  );
}

main();
